/**
 * Voice call keys and the short authentication string.
 *
 * How a Veil call is secured, and why it is layered this way:
 *
 * 1. Call setup travels as ordinary encrypted messages over the Double
 *    Ratchet. So the offer/answer and the media root secret are already
 *    end-to-end encrypted and authenticated by identity keys before any media
 *    flows. There is no separate, weaker call-signalling trust path — which is
 *    the usual weak point in "encrypted calling".
 *
 * 2. Media is protected by SFrame (see sframe.ts) using keys derived here.
 *    This is *inside* WebRTC's own DTLS-SRTP. The reason for both: DTLS-SRTP
 *    terminates at whatever relays the media, so a TURN server or SFU sees
 *    plaintext media. SFrame keys never leave the two endpoints, so a relay
 *    carries ciphertext it cannot open. For a 1:1 call that means the operator
 *    can route the call without being able to listen to it.
 *
 * 3. The SAS lets the two people detect an active MITM by speaking four words
 *    to each other. It is the audible equivalent of a safety number, and it is
 *    bound to the negotiated media secret, so it only matches if both ends
 *    derived the same keys.
 */

import { SHARED_SECRET_LEN, kdf, random, wipe } from './primitives.js';
import { LABELS } from './kdf.js';
import { MalformedInputError } from './errors.js';
import { Writer, concat, utf8 } from './wire.js';
import { type PublicIdentity } from './identity.js';

/** Role in the call. Fixes the ordering of transcript inputs on both ends. */
export type CallRole = 'caller' | 'callee';

export interface CallSecrets {
  /** Root secret for this call; sent inside a ratchet-encrypted setup message. */
  readonly mediaRootSecret: Uint8Array;
}

/** Fresh per-call media secret. Generated by the caller, sent E2EE to the callee. */
export function createCallSecrets(): CallSecrets {
  return { mediaRootSecret: random(SHARED_SECRET_LEN) };
}

/**
 * Transcript binding the call to both identities and both DTLS fingerprints.
 *
 * Including the DTLS certificate fingerprints is what ties the SFrame layer to
 * the actual transport session. Without that, an attacker who relayed the media
 * could pair our SFrame keys with its own DTLS session; with it, the SAS the
 * users compare would differ and the substitution is detectable.
 */
function callTranscript(params: {
  callerIdentity: PublicIdentity;
  calleeIdentity: PublicIdentity;
  callId: Uint8Array;
  callerDtlsFingerprint: Uint8Array;
  calleeDtlsFingerprint: Uint8Array;
}): Uint8Array {
  return new Writer()
    .fixed(utf8.encode('Veil/v1/Call'))
    .bytes(params.callId)
    .bytes(params.callerIdentity.signingPublicKey)
    .bytes(params.calleeIdentity.signingPublicKey)
    .bytes(params.callerDtlsFingerprint)
    .bytes(params.calleeDtlsFingerprint)
    .finish();
}

export interface CallKeyMaterial {
  /** Key we encrypt our outgoing media frames with. */
  readonly sendKey: Uint8Array;
  /** Key we decrypt the peer's frames with. */
  readonly receiveKey: Uint8Array;
  /** Four words both users read aloud to rule out an active MITM. */
  readonly sas: string;
  /** Numeric form, for users who prefer digits or for accessibility tooling. */
  readonly sasDigits: string;
}

/**
 * Derive directional media keys plus the SAS.
 *
 * Send and receive keys are separate and role-derived, so the two directions
 * never share a keystream — reusing one key for both would be a nonce-reuse
 * catastrophe with a stream cipher.
 */
export function deriveCallKeys(params: {
  secrets: CallSecrets;
  role: CallRole;
  callerIdentity: PublicIdentity;
  calleeIdentity: PublicIdentity;
  callId: Uint8Array;
  callerDtlsFingerprint: Uint8Array;
  calleeDtlsFingerprint: Uint8Array;
}): CallKeyMaterial {
  const transcript = callTranscript(params);

  const callerKey = kdf(
    params.secrets.mediaRootSecret,
    transcript,
    concat(LABELS.sframeSender, utf8.encode('/caller')),
    SHARED_SECRET_LEN,
  );
  const calleeKey = kdf(
    params.secrets.mediaRootSecret,
    transcript,
    concat(LABELS.sframeSender, utf8.encode('/callee')),
    SHARED_SECRET_LEN,
  );

  const sasBytes = kdf(params.secrets.mediaRootSecret, transcript, LABELS.callSas, 8);
  const sas = sasWords(sasBytes);
  const sasDigits = sasNumeric(sasBytes);
  wipe(sasBytes, transcript);

  if (params.role === 'caller') {
    return { sendKey: callerKey, receiveKey: calleeKey, sas, sasDigits };
  }
  return { sendKey: calleeKey, receiveKey: callerKey, sas, sasDigits };
}

