/** First four bytes -> four words. ~32 bits of MITM detection, read aloud in seconds. */
export function sasWords(bytes: Uint8Array): string {
  if (bytes.length < 4) {
    throw new MalformedInputError('SAS needs at least 4 bytes');
  }
  if (SAS_WORDS.length !== 256) {
    throw new MalformedInputError(`SAS word list must have exactly 256 entries, has ${SAS_WORDS.length}`);
  }
  return [0, 1, 2, 3].map((i) => SAS_WORDS[bytes[i]!]!).join(' ');
}

/** Numeric SAS: six digits from the same bytes. */
export function sasNumeric(bytes: Uint8Array): string {
  if (bytes.length < 4) {
    throw new MalformedInputError('SAS needs at least 4 bytes');
  }
  let value = 0;
  for (let i = 0; i < 4; i++) value = value * 256 + bytes[i]!;
  return (value % 1_000_000).toString().padStart(6, '0');
}
